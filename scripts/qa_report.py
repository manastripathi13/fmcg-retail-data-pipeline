"""Write the QA report for a run: docs/qa/QA_REPORT_<start>_<end>.md (and docs/qa/LATEST.md).

Summarises qa.datalake_checks and qa.mart_checks for the given range: counts per check and status,
every company-level WoW / YoY breach, the largest region / category breaches, and duplicate rates.

    python scripts/qa_report.py --start 2023-11-14 --end 2026-11-13
"""

import argparse
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from common.config import ROOT, get_spark  # noqa: E402
from common.qa import RULES  # noqa: E402
from common.run_range import add_range_args, resolve  # noqa: E402


def md_table(rows, headers):
    out = ["| " + " | ".join(headers) + " |", "|" + "---|" * len(headers)]
    return out + ["| " + " | ".join("" if v is None else str(v) for v in r) + " |" for r in rows]


ap = argparse.ArgumentParser()
add_range_args(ap)
start, end = resolve(ap.parse_args())
spark = get_spark("qa_report")
run = f"{start}_{end}__%"
q = lambda sql: spark.sql(sql).collect()  # noqa: E731

dl = q(f"""select check_name, table_name, status, count(*) n from qa.datalake_checks where run_id like '{run}'
           group by 1, 2, 3 order by 1, 2, 3""")
dup = q(f"""select round(avg(observed), 3) avg_pct, round(max(observed), 3) max_pct, count(*) days
            from qa.datalake_checks where run_id like '{run}' and check_name = 'pk_uniqueness' and table_name = 'transactions'""")[0]
mt = q(f"""select check_name, level, status, count(*) n from qa.mart_checks where run_id like '{run}'
           group by 1, 2, 3 order by 1, 2, 3""")
breaches = q(f"""select check_name, iso_year, iso_week, observed, detail from qa.mart_checks
                 where run_id like '{run}' and level = 'company' and status = 'FAIL' order by iso_year, iso_week, check_name""")
warns = q(f"""select check_name, level, member, iso_year, iso_week, observed from qa.mart_checks
              where run_id like '{run}' and status = 'WARN' order by abs(observed) desc limit 15""")
pk_fail = q(f"""select table_name, iso_year, iso_week, detail from qa.mart_checks
                where run_id like '{run}' and check_name = 'pk_uniqueness' and status = 'FAIL'""")

wow, yoy = RULES["mart"]["wow_change"]["threshold_abs_pct"], RULES["mart"]["yoy_change"]["threshold_abs_pct"]
md = [f"# QA report: {start} to {end}", "",
      "Generated by `scripts/qa_report.py` from the Hive tables `qa.datalake_checks` and `qa.mart_checks`. Rules: `config/qa_rules.yaml`.", "",
      "## Datalake checks (per daily partition)", ""]
md += md_table([[r.check_name, r.table_name, r.status, f"{r.n:,}"] for r in dl], ["Check", "Table", "Status", "Partitions"])
md += ["", f"Raw POS duplicates in `datalake.transactions`: average {dup.avg_pct}% of lines per day, max {dup.max_pct}% "
       f"(WARN up to {RULES['datalake']['transactions_max_duplicate_pct']}%, FAIL above). They are removed in the mart.", "",
       "## Mart checks (per ISO week)", ""]
md += md_table([[r.check_name, r.level, r.status, f"{r.n:,}"] for r in mt], ["Check", "Level", "Status", "Evaluations"])
md += ["", f"Primary-key uniqueness failures in the mart: **{len(pk_fail)}**.", "",
       f"## Company-level breaches (|WoW| > {wow}% or |YoY| > {yoy}%): {len(breaches)}", "",
       "These fail the `fmcg_4_mart_qa` task for that run and need a business explanation (festival timing, store openings) or a data fix.", ""]
md += md_table([[r.check_name, f"{r.iso_year}-W{r.iso_week:02d}", f"{r.observed:+.1f}%", r.detail] for r in breaches],
               ["Check", "Week", "Change", "Detail"])
md += ["", "## Largest region / category breaches (WARN)", ""]
md += md_table([[r.check_name, r.level, r.member, f"{r.iso_year}-W{r.iso_week:02d}", f"{r.observed:+.1f}%"] for r in warns],
               ["Check", "Level", "Member", "Week", "Change"])
text = "\n".join(md) + "\n"
out = ROOT / "docs" / "qa" / f"QA_REPORT_{start}_{end}.md"
out.parent.mkdir(parents=True, exist_ok=True)
out.write_text(text)
(out.parent / "LATEST.md").write_text(text)
print(text)
